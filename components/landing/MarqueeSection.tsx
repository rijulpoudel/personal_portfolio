function MarqueeRow({
  urls,
  rowRef,
  initialTransform,
}: {
  urls: string[];
  rowRef: RefObject<HTMLDivElement | null>;
  initialTransform: string;
}) {
  return (
    <div
      ref={rowRef}
      className="flex gap-3"
      style={{ willChange: "transform", transform: initialTransform }}
    >
      {[...urls, ...urls, ...urls].map((src, i) => (
        // eslint-disable-next-line @next/next/no-img-element
        <img
          key={`${src}-${i}`}
          src={src}
          alt=""
          loading="lazy"
          className="h-[270px] w-[420px] flex-shrink-0 rounded-2xl object-cover"
        />
      ))}
    </div>
  );
}

export default function MarqueeSection() {
  const sectionRef = useRef<HTMLElement>(null);
  const row1Ref = useRef<HTMLDivElement>(null);
  const row2Ref = useRef<HTMLDivElement>(null);

  useEffect(() => {
    let raf = 0;

    const update = () => {
      const section = sectionRef.current;
      if (!section) return;
      const offset = (window.scrollY - section.offsetTop + window.innerHeight) * 0.3;
      if (row1Ref.current) {
        row1Ref.current.style.transform = `translateX(${offset - 200}px)`;
      }
      if (row2Ref.current) {
        row2Ref.current.style.transform = `translateX(${-(offset - 200)}px)`;
      }
    };

    const onScroll = () => {
      cancelAnimationFrame(raf);
      raf = requestAnimationFrame(update);
    };

    update();
    window.addEventListener("scroll", onScroll, { passive: true });
    return () => {
      window.removeEventListener("scroll", onScroll);
      cancelAnimationFrame(raf);
    };
  }, []);

  return (
    <section
      ref={sectionRef}
      className="overflow-x-clip bg-[#0C0C0C] pb-10 pt-24 sm:pt-32 md:pt-40"
    >
      <div className="flex flex-col gap-3">
        <MarqueeRow urls={ROW_1} rowRef={row1Ref} initialTransform="translateX(-200px)" />
        <MarqueeRow urls={ROW_2} rowRef={row2Ref} initialTransform="translateX(200px)" />
      </div>
    </section>
  );
}
